func hexRGB(h string) (r, g, b float64) {
	v, _ := strconv.ParseUint(strings.TrimPrefix(h, "#"), 16, 32)
	return float64(v >> 16 & 255), float64(v >> 8 & 255), float64(v & 255)
}

func lin(c float64) float64 {
	c /= 255
	if c <= 0.03928 {
		return c / 12.92
	}
	return math.Pow((c+0.055)/1.055, 2.4)
}

// Contrast is the WCAG contrast ratio of two #RRGGBB colours.
func Contrast(a, b string) float64 {
	ar, ag, ab := hexRGB(a)
	br, bg, bb := hexRGB(b)
	la := 0.2126*lin(ar) + 0.7152*lin(ag) + 0.0722*lin(ab)
	lb := 0.2126*lin(br) + 0.7152*lin(bg) + 0.0722*lin(bb)
	if la < lb {
		la, lb = lb, la
	}
	return (la + 0.05) / (lb + 0.05)
}

// AccentReadable reports whether the accent reads as text (4.5:1) on both
// themes' page and inset backgrounds, and whether the muted and secondary text
// do too.
func AccentReadable(name string) bool {
	a, ok := accents[name]
	if !ok {
		return false
	}
	pairs := [][2]string{
		{a.light, lightBG}, {a.light, lightBG2}, {a.dark, darkBG}, {a.dark, darkBG2},
		{lightFG, lightBG}, {lightFG2, lightBG}, {lightMuted, lightBG}, {lightMuted, lightBG2},
		{darkFG, darkBG}, {darkFG2, darkBG}, {darkMuted, darkBG}, {darkMuted, darkBG2},
	}
	for _, p := range pairs {
		if Contrast(p[0], p[1]) < 4.5 {
			return false
		}
	}
	return true
}

