	lightBG, lightBG2, lightFG, lightFG2, lightMuted, lightLine = "#FBFAF7", "#F4F2EC", "#1C1B18", "#4A4740", "#726D63", "#E2DED5"
	darkBG, darkBG2, darkFG, darkFG2, darkMuted, darkLine       = "#131311", "#232320", "#EDEAE3", "#C4C0B6", "#8E897E", "#2E2D28"
