// The site's colours are the app's Paper and Ink themes; the accent is the one
// thing the owner chooses, from a short list, and each is checked here against
// the text colours of both themes (the same 4.5:1 rule scripts/check-contrast.py
// holds the app to). A choice that fails never reaches a stylesheet.
type accent struct{ light, dark string }

